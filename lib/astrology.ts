// 根據星座代碼取得完整資料
export function getSignData(sign: string): SignData | undefined {
  return zodiacSigns.find((s) => s.sign.toLowerCase() === sign.toLowerCase());
}

// 取得所有星座的今日簡短運勢（用於首頁）
export function getAllSignsTodayPreview() {
  return zodiacSigns.map((s) => ({
    sign: s.sign,
    name: s.name,
    emoji: s.emoji,
    preview: s.today.love, // 使用愛情運勢作為預覽
  }));
}

// 根據英文星座名取得中文名
export function getSignName(sign: string): string {
  const signData = getSignData(sign);
  return signData ? signData.name : sign;
}
